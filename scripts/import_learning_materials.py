class AutoPromptEngineer:
    def __init__(self, llm_client, eval_dataset):
        self.llm = llm_client
        self.dataset = eval_dataset
    
    def generate_candidates(self, task_desc, n=20):
        """生成N个候选提示词"""
        prompt = f"""
        基于以下任务描述，生成{n}个不同风格的提示词变体：
        
        任务：{task_desc}
        
        要求：
        - 每个提示词都要有不同的侧重点
        - 有的简短有力，有的详细全面
        - 有的正式，有的口语化
        
        请以编号列表形式输出。
        """
        response = self.llm.generate(prompt)
        return self.parse_candidates(response)
    
    def evaluate(self, candidate_prompt):
        """评估单个提示词的效果"""
        scores = []
        for example in self.dataset:
            output = self.llm.generate(
                candidate_prompt.format(input=example['input'])
            )
            score = self.compute_metric(output, example['expected'])
            scores.append(score)
        return {
            'mean': sum(scores)/len(scores),
            'std': self.std_dev(scores),
            'min': min(scores),
            'max': max(scores)
        }
    
    def select_best(self, candidates_evaluations):
        """选择最优提示词"""
        return max(
            candidates_evaluations.items(),
            key=lambda x: x[1]['mean']
        )

